import { useQuery, useQueryClient } from '@tanstack/react-query'
import { useState } from 'react'
import { api } from '../api'
import { Card } from './Card'

const PRIORITY = { high: 'bg-red-100 text-red-700', medium: 'bg-amber-100 text-amber-800', low: 'bg-slate-100 text-slate-600' }

export function InsightsPanel({ onSelect }: { onSelect: (sku: string) => void }) {
  const qc = useQueryClient()
  const [refreshing, setRefreshing] = useState(false)
  const { data, isLoading, error } = useQuery({ queryKey: ['insights'], queryFn: () => api.insights() })

  const refresh = async () => {
    setRefreshing(true)
    try {
      qc.setQueryData(['insights'], await api.insights(true))
    } finally {
      setRefreshing(false)
    }
  }

  return (
    <Card
      title={
        <span className="flex items-center gap-2">
          <span className="text-indigo-500">✦</span> AI briefing
        </span>
      }
      action={
        <button onClick={refresh} disabled={refreshing || isLoading} className="text-xs font-medium text-indigo-600 hover:text-indigo-800 disabled:opacity-50">
          {refreshing ? 'Generating…' : 'Regenerate'}
        </button>
      }
    >
      {isLoading || refreshing ? (
        <div className="space-y-2">
          {[...Array(6)].map((_, i) => (
            <div key={i} className="h-4 animate-pulse rounded bg-slate-100" style={{ width: `${90 - i * 8}%` }} />
          ))}
          <p className="pt-2 text-xs text-slate-500">Analyzing forecasts and stock positions…</p>
        </div>
      ) : error || !data ? (
        <p className="text-sm text-red-600">{String(error)}</p>
      ) : (
        <div className="space-y-5 text-sm">
          <div>
            <p className="text-base font-semibold leading-snug text-slate-900">{data.headline}</p>
            <p className="mt-1.5 leading-relaxed text-slate-600">{data.summary}</p>
          </div>

          <div>
            <h3 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-500">Recommended actions</h3>
            <ul className="space-y-2">
              {data.actions.map((a, i) => (
                <li key={i} className="flex gap-2">
                  <span className={`mt-0.5 h-fit rounded px-1.5 py-0.5 text-[10px] font-semibold uppercase ${PRIORITY[a.priority]}`}>{a.priority}</span>
                  <div>
                    <p className="font-medium text-slate-800">{a.action}</p>
                    <p className="text-xs text-slate-500">{a.rationale}</p>
                  </div>
                </li>
              ))}
            </ul>
          </div>

          <div>
            <h3 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-500">Key risks</h3>
            <ul className="space-y-2">
              {data.key_risks.map((r) => (
                <li key={r.sku} className="rounded-lg border border-slate-100 p-2.5 hover:border-indigo-200">
                  <button onClick={() => onSelect(r.sku)} className="text-xs font-semibold text-indigo-600 hover:underline">
                    {r.sku}
                  </button>
                  <p className="text-slate-700">{r.issue}</p>
                  <p className="mt-0.5 text-xs text-slate-500">→ {r.recommendation}</p>
                </li>
              ))}
            </ul>
          </div>

          <div>
            <h3 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-500">Trends</h3>
            <ul className="list-disc space-y-1 pl-4 text-slate-600">
              {data.trends.map((t, i) => (
                <li key={i}>{t}</li>
              ))}
            </ul>
          </div>

          <p className="border-t border-slate-100 pt-3 text-[11px] text-slate-400">
            {data.source === 'llm' ? `Generated by ${data.model}` : 'Rules-based summary (set ANTHROPIC_API_KEY for AI-generated briefings)'}
          </p>
        </div>
      )}
    </Card>
  )
}
